// Precompute badge stats and per-number scores.
// Run: npm run precompute   (npx tsx scripts/precompute.ts)
//
// Writes:
//   supabase/seed.sql               badge catalogue (committed)
//   supabase/seed/number_stats.csv  number,ep,tier,badge_ids (gitignored)
//   lib/badges/stats.json           badge odds + EP distribution for the UI (committed)

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { TOTAL_NUMBERS, bestPerFamily, computeBadgeStats, tiersForEps, type Tier } from "../lib/badges";
import { MIN_ROLL } from "../lib/badges/helpers";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const t0 = Date.now();

const { stats, matches } = computeBadgeStats();
const epById = new Map(stats.map((st) => [st.badge.id, st.ep]));

for (const st of stats) {
  if (st.count < 1) throw new Error(`badge ${st.badge.slug} matches no numbers`);
}

// Only the best badge per family counts (see lib/badges/index.ts).
const eps = new Int32Array(TOTAL_NUMBERS);
const counted: number[][] = new Array(TOTAL_NUMBERS);
for (let i = 0; i < TOTAL_NUMBERS; i++) {
  counted[i] = bestPerFamily(matches[i], epById);
  let ep = 0;
  for (const id of counted[i]) ep += epById.get(id)!;
  eps[i] = ep;
}
const tierByEp = tiersForEps(eps);

// --- summary -----------------------------------------------------------------
console.log("Badges");
console.table(
  stats.map((st) => ({
    id: st.badge.id,
    slug: st.badge.slug,
    family: st.badge.family,
    count: st.count,
    probability: Number(st.probability.toPrecision(4)),
    rarity: st.rarity,
    ep: st.ep,
  })),
);

const tierCounts = new Map<Tier, { count: number; minEp: number; maxEp: number }>();
for (const [ep, tier] of tierByEp) {
  const c = tierCounts.get(tier) ?? { count: 0, minEp: Infinity, maxEp: -Infinity };
  c.minEp = Math.min(c.minEp, ep);
  c.maxEp = Math.max(c.maxEp, ep);
  tierCounts.set(tier, c);
}
for (let i = 0; i < TOTAL_NUMBERS; i++) tierCounts.get(tierByEp.get(eps[i])!)!.count++;
const order: Tier[] = ["mythic", "anomaly", "epic", "rare", "uncommon", "common", "trash"];
console.log("Tiers");
console.table(
  order.map((tier) => {
    const c = tierCounts.get(tier);
    return {
      tier,
      numbers: c?.count ?? 0,
      share: c ? `${((100 * c.count) / TOTAL_NUMBERS).toFixed(2)}%` : "0%",
      minEp: c?.minEp ?? "-",
      maxEp: c?.maxEp ?? "-",
    };
  }),
);

// --- seed.sql ----------------------------------------------------------------
const q = (v: string) => `'${v.replace(/'/g, "''")}'`;
const rows = stats.map(
  (st) =>
    `  (${st.badge.id}, ${q(st.badge.slug)}, ${q(st.badge.name)}, ${q(st.badge.emoji)}, ${q(st.badge.family)}, ${q(st.badge.description)}, ${q(st.rarity)}, ${st.probability}, ${st.ep})`,
);
const sql = `-- Generated by scripts/precompute.ts. Do not edit by hand; run \`npm run precompute\`.
-- number_stats is loaded separately from supabase/seed/number_stats.csv.
-- Upsert, so it also updates an existing catalogue (ids are stable).

insert into public.badges (id, slug, name, emoji, family, description, rarity, probability, ep) values
${rows.join(",\n")}
on conflict (id) do update set
  slug = excluded.slug, name = excluded.name, emoji = excluded.emoji, family = excluded.family,
  description = excluded.description, rarity = excluded.rarity,
  probability = excluded.probability, ep = excluded.ep;
`;
writeFileSync(join(root, "supabase/seed.sql"), sql);

// --- number_stats.csv --------------------------------------------------------
const csvPath = join(root, "supabase/seed/number_stats.csv");
mkdirSync(dirname(csvPath), { recursive: true });
const lines: string[] = new Array(TOTAL_NUMBERS);
for (let i = 0; i < TOTAL_NUMBERS; i++) {
  lines[i] = `${i + MIN_ROLL},${eps[i]},${tierByEp.get(eps[i])},"{${counted[i].join(",")}}"`;
}
writeFileSync(csvPath, lines.join("\n") + "\n");

// --- stats.json (client-side odds and percentiles) ---------------------------
// epAtLeast: [ep, how many numbers score >= ep] for each distinct EP, ascending.
const epCounts = new Map<number, number>();
for (let i = 0; i < TOTAL_NUMBERS; i++) epCounts.set(eps[i], (epCounts.get(eps[i]) ?? 0) + 1);
const distinct = [...epCounts.keys()].sort((a, b) => a - b);
let atLeast = TOTAL_NUMBERS;
const epAtLeast: [number, number][] = [];
for (const ep of distinct) {
  epAtLeast.push([ep, atLeast]);
  atLeast -= epCounts.get(ep)!;
}
const statsJson = {
  total: TOTAL_NUMBERS,
  badgeCounts: Object.fromEntries(stats.map((st) => [st.badge.slug, st.count])),
  epAtLeast,
};
writeFileSync(join(root, "lib/badges/stats.json"), JSON.stringify(statsJson) + "\n");

console.log(`Wrote supabase/seed.sql, lib/badges/stats.json and supabase/seed/number_stats.csv in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
